#!/usr/bin/env python3
"""Generate AlgNames.h (effect algorithm code -> name) for the Arduino sketches.

Reads all *alg_data.json / algorithm.json files of the editor; newer files win.
Usage: gen_alg_names.py <editor data dir> <output header>
"""
import glob
import json
import os
import sys


def load(path):
    j = json.load(open(path, encoding='utf-8'))
    out = {}
    for cat in j['PluginProperties']['Modules']['Catalog']:
        for a in cat['Alg']:
            out[int(a['Code'])] = a['Name'].strip()
    return out


def main():
    src, dst = sys.argv[1], sys.argv[2]
    files = [os.path.join(src, 'algorithm.json')] + sorted(glob.glob(os.path.join(src, 'v*_alg_data.json')))
    names = {}
    for f in files:
        names.update(load(f))
    with open(dst, 'w', encoding='utf-8', newline='\n') as o:
        o.write('#pragma once\n')
        o.write('// Generated by tools/gen_alg_names.py from the editor\'s algorithm databases - do not edit.\n')
        o.write('#include <stdint.h>\n\n')
        o.write('struct AlgName {\n  uint32_t code;\n  const char* name;\n};\n\n')
        o.write('static const AlgName kAlgNames[] = {\n')
        for code in sorted(names):
            n = names[code].encode('ascii', 'replace').decode().replace('\\', '\\\\').replace('"', '\\"')
            o.write('    {%d, "%s"},\n' % (code, n))
        o.write('};\n\n')
        o.write('/** Name of an effect algorithm, nullptr if unknown (table is sorted by code). */\n')
        o.write('inline const char* algName(uint32_t code) {\n')
        o.write('  int lo = 0, hi = (int)(sizeof kAlgNames / sizeof kAlgNames[0]) - 1;\n')
        o.write('  while (lo <= hi) {\n')
        o.write('    const int mid = (lo + hi) / 2;\n')
        o.write('    if (kAlgNames[mid].code == code) return kAlgNames[mid].name;\n')
        o.write('    if (kAlgNames[mid].code < code) lo = mid + 1; else hi = mid - 1;\n')
        o.write('  }\n  return nullptr;\n}\n')
    print('%d names -> %s' % (len(names), dst))


if __name__ == '__main__':
    main()
